export type Locale = 'en' | 'ar' | 'es' | 'pt' | 'id' | 'hi'
export type ErrorKey = keyof Messages['errors']

const MESSAGES: Record<Locale, Messages> = { en, ar, es, pt, id, hi }

export const LOCALES: { code: Locale; name: string }[] = [
  { code: 'en', name: 'English' },
  { code: 'ar', name: 'العربية' },
  { code: 'es', name: 'Español' },
  { code: 'pt', name: 'Português' },
  { code: 'id', name: 'Bahasa Indonesia' },
  { code: 'hi', name: 'हिन्दी' },
]

const STORAGE_KEY = 'locale'

function browserLocale(): Locale {
  const code = navigator.language.slice(0, 2).toLowerCase()
  if (code === 'in') return 'id'
  return code in MESSAGES ? (code as Locale) : 'en'
}

const locale = shallowRef<Locale>(browserLocale())
storageGet<Locale>(STORAGE_KEY).then((saved) => {
  if (saved && saved in MESSAGES) locale.value = saved
})

export function useI18n() {
  const t = computed(() => MESSAGES[locale.value])
  const dir = computed(() => (locale.value === 'ar' ? 'rtl' : 'ltr'))
  function setLocale(next: Locale) {
    locale.value = next
    storageSet({ [STORAGE_KEY]: next })
  }
  function errorText(code: string | null | undefined): string {
    if (!code) return ''
    return t.value.errors[code as ErrorKey] ?? t.value.errors.unknown
  }
  return { locale, t, dir, setLocale, errorText }
}
